// Lock the admin site's GitHub token with a password.
//
//   ADMIN_PASSWORD="..." node scripts/admin-vault.mjs
//
// Reads ADMIN_GITHUB_TOKEN from .env (a fine-grained token for this repo only)
// and writes admin/vault.js: the token encrypted with AES-256-GCM, key derived
// from the password with PBKDF2-SHA256 (600k iterations). The page decrypts it
// in the browser; without the password the file is useless.

import { writeFileSync } from "node:fs";
import { env } from "./meta.mjs";

const password = process.env.ADMIN_PASSWORD;
if (!password || password.length < 16) throw new Error("set ADMIN_PASSWORD (16+ characters)");
const token = env("ADMIN_GITHUB_TOKEN");

const { subtle } = globalThis.crypto;
const salt = crypto.getRandomValues(new Uint8Array(16));
const iv = crypto.getRandomValues(new Uint8Array(12));
const base = await subtle.importKey("raw", new TextEncoder().encode(password), "PBKDF2", false, ["deriveKey"]);
const key = await subtle.deriveKey({ name: "PBKDF2", salt, iterations: 600000, hash: "SHA-256" }, base, { name: "AES-GCM", length: 256 }, false, ["encrypt"]);
const ct = new Uint8Array(await subtle.encrypt({ name: "AES-GCM", iv }, key, new TextEncoder().encode(token)));

const b64 = (u) => Buffer.from(u).toString("base64");
writeFileSync(new URL("../admin/vault.js", import.meta.url),
  `// Generated by scripts/admin-vault.mjs. Encrypted; needs the admin password.\nexport const VAULT = ${JSON.stringify({ salt: b64(salt), iv: b64(iv), ct: b64(ct), iterations: 600000 })};\n`);
console.log("admin/vault.js written");
